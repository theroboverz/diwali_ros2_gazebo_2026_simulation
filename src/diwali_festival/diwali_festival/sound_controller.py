"""Sound architecture.

Gazebo Harmonic has no general-purpose "play this audio file" topic, so audio is played by the
festival node on the HOST using a command-line player (first one found):
paplay (pulseaudio-utils) > aplay (alsa-utils) > ffplay (ffmpeg) > play (sox).
Sounds are therefore not spatialised and are not recorded by Gazebo. WAV files are synthetic and
generated by diwali_sim/scripts/generate_assets.py (no third-party audio).
"""
import shutil
import subprocess
from pathlib import Path

PLAYERS = [('paplay', []), ('aplay', ['-q']), ('ffplay', ['-nodisp', '-autoexit', '-loglevel', 'quiet']),
           ('play', ['-q'])]


class SoundController:
    def __init__(self, sounds_dir, enabled=True, max_concurrent=6, logger=None):
        self.dir = Path(sounds_dir)
        self.enabled = enabled
        self.max_concurrent = max_concurrent
        self._log = logger
        self._procs = []
        self.player = None
        for exe, args in PLAYERS:
            path = shutil.which(exe)
            if path:
                self.player = [path] + args
                break
        if logger:
            logger.info(f'Sound player: {self.player[0] if self.player else "none found (sound disabled)"}')

    def available(self):
        return sorted(p.stem for p in self.dir.glob('*.wav'))

    def play(self, name):
        if not self.enabled or not self.player:
            return False
        f = self.dir / f'{name}.wav'
        if not f.exists():
            if self._log:
                self._log.warn(f'Unknown sound "{name}"; available: {self.available()}')
            return False
        self._procs = [p for p in self._procs if p.poll() is None]
        if len(self._procs) >= self.max_concurrent:
            return False
        self._procs.append(subprocess.Popen(self.player + [str(f)], stdout=subprocess.DEVNULL,
                                            stderr=subprocess.DEVNULL))
        return True
